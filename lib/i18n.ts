export function localePath(locale: Locale, path = "") {
  return `/${locale}${path}`;
}

export function switchLocalePath(pathname: string, nextLocale: Locale) {
  const stripped = pathname.replace(/^\/(vi|en)(?=\/|$)/, "");
  return `/${nextLocale}${stripped || ""}`;
}

